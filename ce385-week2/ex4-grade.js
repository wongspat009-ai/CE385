// ฟังก์ชันแปลงคะแนนเป็นเกรด รับคะแนน (score) แล้วคืนค่าเกรดเป็นข้อความ
function toGrade(score) {
  // ตรวจสอบข้อมูลนำเข้าก่อนตัดเกรดเสมอ (สำคัญมากสำหรับงาน Backend)
  // ถ้าคะแนนน้อยกว่า 0 หรือมากกว่า 100 แสดงว่าข้อมูลผิดพลาด ต้องไม่ตัดเกรดให้
  if (score < 0 || score > 100) {
    return "คะแนนไม่ถูกต้อง ต้องอยู่ระหว่าง 0-100";
  }

  // ต้องเรียงเงื่อนไขจากคะแนนมากไปน้อยเสมอ เพราะ if/else if จะหยุดตรวจ
  // ทันทีที่เจอเงื่อนไขแรกที่เป็นจริง ถ้าเรียงจากน้อยไปมากจะตัดเกรดผิด
  // เช่น ถ้าตรวจ score >= 0 ก่อน คะแนน 95 ก็จะเข้าเงื่อนไขนี้ทันทีทั้งที่ควรได้ A
  if (score >= 80) {
    return "A";
  } else if (score >= 75) {
    return "B+";
  } else if (score >= 70) {
    return "B";
  } else if (score >= 65) {
    return "C+";
  } else if (score >= 60) {
    return "C";
  } else if (score >= 55) {
    return "D+";
  } else if (score >= 50) {
    return "D";
  } else {
    return "F";
  }
}

// ===== ส่วนที่ 3: ทดสอบให้ครบทุกค่า =====
// สร้างเป็น array แล้วใช้ for...of วนทดสอบ จะได้ไม่ต้องเขียนซ้ำ 13 รอบ
const testScores = [95, 80, 79, 75, 70, 65, 60, 55, 50, 49, 0, -5, 120];

for (const score of testScores) {
  console.log(`คะแนน ${score} → เกรด ${toGrade(score)}`);
}