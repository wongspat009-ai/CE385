// ข้อมูลบัญชีที่ถูกต้องในระบบ
const USERNAME = "admin";
const PASSWORD = "ce385pass";

// ===== ส่วนที่ 1: ฟังก์ชันตรวจสอบสิทธิ์ =====
// ฟังก์ชันนี้ "คืนค่า" ข้อความผลลัพธ์เท่านั้น ไม่ log เอง
// เพื่อให้เอาไปใช้ต่อได้ยืดหยุ่น (เช่น ส่งเป็น HTTP response code จริงในงาน Backend)
function login(inputUser, inputPass, role, isActive, age) {
  // ลำดับที่ 1: ตรวจ username/password ก่อนเป็นอันดับแรกเสมอ
  if (inputUser !== USERNAME || inputPass !== PASSWORD) {
    return "ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง"; // เทียบกับ 401
  }

  // ลำดับที่ 2: ตรวจว่าบัญชีถูกระงับหรือไม่
  if (isActive === false) {
    return "บัญชีนี้ถูกระงับการใช้งาน"; // เทียบกับ 403
  }

  // ลำดับที่ 3: ตรวจอายุขั้นต่ำ
  if (age < 18) {
    return "อายุไม่ถึงเกณฑ์";
  }

  // ลำดับที่ 4 และ 5: ผ่านทุกข้อแล้ว แยกสิทธิ์ตาม role
  if (role === "อาจารย์") {
    return "เข้าสู่ระบบสำเร็จ (สิทธิ์ผู้ดูแล)"; // เทียบกับ 200
  } else if (role === "นักศึกษา") {
    return "เข้าสู่ระบบสำเร็จ (สิทธิ์ทั่วไป)"; // เทียบกับ 200
  }

  // กรณี role ไม่ตรงกับที่ระบบรู้จักเลย (ไม่ใช่ทั้งอาจารย์และนักศึกษา)
  return "บทบาทผู้ใช้ไม่ถูกต้อง";
}

// ===== ส่วนที่ 2: ทดสอบอย่างน้อย 6 กรณี =====
console.log(`1) สำเร็จ (อาจารย์): ${login("admin", "ce385pass", "อาจารย์", true, 30)}`);
console.log(`2) สำเร็จ (นักศึกษา): ${login("admin", "ce385pass", "นักศึกษา", true, 20)}`);
console.log(`3) รหัสผ่านผิด: ${login("admin", "wrongpass", "อาจารย์", true, 30)}`);
console.log(`4) ชื่อผู้ใช้ผิด: ${login("someone", "ce385pass", "นักศึกษา", true, 20)}`);
console.log(`5) บัญชีถูกระงับ: ${login("admin", "ce385pass", "นักศึกษา", false, 20)}`);
console.log(`6) อายุไม่ถึง: ${login("admin", "ce385pass", "นักศึกษา", true, 15)}`);

// ===== ส่วนที่ 3: ตอบคำถามท้ายข้อ (เขียนเป็น comment) =====

// คำถามที่ 1: ทำไมต้องตรวจ username/password ก่อน ตรวจ role
// เพราะ username/password คือการยืนยัน "ตัวตน" (Authentication) ว่าคน ๆ นี้
// เป็นใครในระบบจริงหรือไม่ ส่วน role คือการตรวจ "สิทธิ์" (Authorization) ว่า
// ตัวตนนั้นทำอะไรได้บ้าง ถ้ายังไม่รู้ว่าเป็นใครแน่ชัด (ยืนยันตัวตนไม่ผ่าน)
// การไปเช็ค role ก่อนก็ไม่มีความหมาย เพราะเราไม่ควรไว้ใจค่า role ที่ส่งเข้ามา
// จากคนที่ยังพิสูจน์ตัวตนไม่ได้เลย จึงต้องเรียงลำดับ Authentication ก่อน
// Authorization เสมอ

// คำถามที่ 2: ถ้าย้ายการตรวจ "อายุไม่ถึงเกณฑ์" ขึ้นไปเป็นข้อแรก จะเกิดปัญหาอะไร
// (คิดในแง่ความปลอดภัย: เราจะบอกอะไรกับคนที่ยังไม่ได้พิสูจน์ตัวตน)
// ถ้าตรวจอายุก่อนตรวจ username/password ระบบจะเผยข้อมูลภายใน (ว่ามีเกณฑ์อายุ
// ผูกอยู่กับบัญชีนี้) ให้กับคนที่ยังไม่ได้ยืนยันตัวตนเลยด้วยซ้ำ ถือเป็นการรั่วไหล
// ข้อมูล (Information Leakage) และยังเปิดช่องให้ผู้ไม่หวังดีสุ่มทดสอบอายุของ
// บัญชีคนอื่นได้ทั้งที่ยังไม่มีสิทธิ์เข้าถึงข้อมูลนั้นเลย หลักการที่ถูกต้องคือ
// ต้องปิดกั้นคนที่ยืนยันตัวตนไม่ผ่านตั้งแต่ขั้นแรกสุด ก่อนจะเปิดเผยเงื่อนไข
// ภายในอื่น ๆ ของระบบ